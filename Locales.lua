-- proxy, so files can keep a local L; missing keys fall back to english
---@type table<string, any>
local active = ns.LOCALES.en
ns.L = setmetatable({}, {
  __index = function(_, key) return active[key] or ns.LOCALES.en[key] or key end,
})

function ns.SetLanguage(code)
  active = ns.LOCALES[code] or ns.LOCALES.en
end
